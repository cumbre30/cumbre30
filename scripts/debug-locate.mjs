import { chromium } from "playwright";
const BASE = "http://localhost:3000/";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, geolocation: { latitude: -33.4505, longitude: -70.67, accuracy: 12 }, permissions: ["geolocation"] });
const page = await ctx.newPage();
page.on("console", (m) => { if (/gps|ubic|pos/i.test(m.text())) console.log("[console]", m.text().slice(0,120)); });
await page.goto(BASE, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.getByRole("button", { name: "Explorar" }).click();
await page.waitForTimeout(5000);
const t1 = await page.evaluate(() => document.querySelector(".leaflet-map-pane")?.style.transform ?? "");
console.log("t1 =", t1);
const btn = page.locator("button[title='Centrar en mi ubicación']").first();
console.log("btn count:", await page.locator("button[title='Centrar en mi ubicación']").count());
await btn.click();
await page.waitForTimeout(2500);
const t3 = await page.evaluate(() => document.querySelector(".leaflet-map-pane")?.style.transform ?? "");
console.log("t3 =", t3, "· cambió:", t3 !== t1);
await browser.close();
