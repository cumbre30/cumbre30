import { chromium } from "playwright";
const BASE = "http://localhost:3000/";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await ctx.newPage();
await page.goto(BASE, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await ctx.grantPermissions(["geolocation"]);
await ctx.setGeolocation({ latitude: -33.4307, longitude: -70.6359, accuracy: 8 });
await page.waitForTimeout(1000);
await page.locator("button", { hasText: "Iniciar ride" }).first().click();
await page.waitForTimeout(4000);
console.log("[selects]", await page.locator("select").count());
const sel = page.locator("select[aria-label='Ir a']");
console.log("[visible]", await sel.isVisible().catch((e) => "ERR " + e.message.slice(0, 60)));
const box = await sel.boundingBox().catch(() => null);
console.log("[boundingBox]", JSON.stringify(box));
await page.screenshot({ path: "/tmp/render/ride-con-gps.png", fullPage: true });
await browser.close();
